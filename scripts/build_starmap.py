#!/usr/bin/env python3
"""Build site/js/data/starmap.js: bright stars, constellation lines and labels
for the satellite sky view, from d3-celestial's data files (Hipparcos-based,
BSD-3-Clause, (c) Olaf Frohn).

Run:  python3 scripts/build_starmap.py [d3-celestial version]

Coordinates are J2000 degrees. Only what can rise at Socorro (dec > DEC_MIN)
is kept, rounded to 0.01 deg (about 0.02 px on the polar plot).
"""
import json
import sys
import urllib.request
from pathlib import Path

VERSION = sys.argv[1] if len(sys.argv) > 1 else "0.7.35"
BASE = f"https://cdn.jsdelivr.net/npm/d3-celestial@{VERSION}/data/"
OUT = Path(__file__).resolve().parent.parent / "site/js/data/starmap.js"
MAG_LIMIT = 4.0     # faintest star drawn
NAME_LIMIT = 1.6    # stars at least this bright get a name label
DEC_MIN = -60.0     # Socorro is at +34 deg; the southern horizon is dec -56


def get(name):
    with urllib.request.urlopen(BASE + name) as r:
        return json.load(r)


def ra(x):
    return round(x % 360, 2)


def main():
    stars = get("stars.6.json")["features"]
    names = get("starnames.json")
    lines = get("constellations.lines.json")["features"]
    cons = get("constellations.json")["features"]

    star_rows, named = [], []
    for f in sorted(stars, key=lambda f: f["properties"]["mag"]):
        mag = f["properties"]["mag"]
        lon, dec = f["geometry"]["coordinates"]
        if mag > MAG_LIMIT or dec < DEC_MIN:
            continue
        bv = f["properties"].get("bv")
        bv = round(float(bv), 2) if bv not in (None, "") else 0.6
        star_rows.append([ra(lon), round(dec, 2), mag, bv])
        name = names.get(str(f["id"]), {}).get("name")
        if mag <= NAME_LIMIT and name:
            named.append([len(star_rows) - 1, name])

    line_rows = []
    for f in lines:
        for seg in f["geometry"]["coordinates"]:
            if max(p[1] for p in seg) < DEC_MIN:
                continue
            line_rows.append([v for p in seg for v in (ra(p[0]), round(p[1], 2))])

    label_rows = []
    for f in cons:
        lon, dec = f["geometry"]["coordinates"]
        if dec < DEC_MIN:
            continue
        p = f["properties"]
        label_rows.append([ra(lon), round(dec, 2), p["name"], int(p["rank"])])

    dump = lambda x: json.dumps(x, separators=(",", ":"), ensure_ascii=False)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/build_starmap.py from d3-celestial "
        f"{VERSION} data (Hipparcos; BSD-3-Clause, (c) Olaf Frohn).\n"
        "// J2000 degrees. Do not edit by hand.\n"
        f"// Stars to mag {MAG_LIMIT}, sorted bright first: [ra, dec, mag, B-V].\n"
        f"export const STARS = {dump(star_rows)};\n"
        "// Named bright stars: [index into STARS, name].\n"
        f"export const STAR_NAMES = {dump(named)};\n"
        "// Constellation stick figures: flat [ra, dec, ra, dec, ...] polylines.\n"
        f"export const LINES = {dump(line_rows)};\n"
        "// Constellation labels: [ra, dec, name, rank (1 = most prominent)].\n"
        f"export const LABELS = {dump(label_rows)};\n",
        encoding="utf-8",
    )
    print(f"{OUT}: {len(star_rows)} stars, {len(named)} names, "
          f"{len(line_rows)} lines, {len(label_rows)} labels, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
