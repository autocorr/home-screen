#!/usr/bin/env python3
"""Build site/js/data/satmags.js: standard magnitudes for CelesTrak's "visual"
group (the ~150 brightest satellites), from Mike McCants' quicksat magnitude
file (https://www.mmccants.org/programs/qsmag.zip).

A standard magnitude is the brightness at 1000 km range, half illuminated
(90° phase angle). Objects McCants has no value for are left out; the page
falls back to SATS.stdMag in config.js, then SATS.defaultStdMag.

Run:  python3 scripts/build_satmags.py [extra catalog numbers...]
"""
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

QSMAG = "https://www.mmccants.org/programs/qsmag.zip"
GROUP = "https://celestrak.org/NORAD/elements/gp.php?GROUP=visual&FORMAT=tle"
OUT = Path(__file__).resolve().parent.parent / "site/js/data/satmags.js"
EXTRA = [53807]  # SATS.extra in config.js: not in the visual group


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "home-screen build script"})
    with urllib.request.urlopen(req) as r:
        return r.read()


def main():
    extra = [int(x) for x in sys.argv[1:]] or EXTRA
    group = get(GROUP).decode()
    ids = sorted({int(l[2:7]) for l in group.splitlines() if l.startswith("1 ")} | set(extra))

    z = zipfile.ZipFile(io.BytesIO(get(QSMAG)))
    info = z.infolist()[0]
    mags = {}
    for line in z.read(info).decode("latin-1").splitlines()[1:]:
        try:
            cat, mag = int(line[:5]), float(line[33:38])
        except ValueError:
            continue
        mags[cat] = mag
    found = {i: mags[i] for i in ids if i in mags}
    date = "%04d-%02d-%02d" % info.date_time[:3]

    body = ",".join(f"{k}:{v:g}" for k, v in sorted(found.items()))
    OUT.write_text(
        f"// Generated by scripts/build_satmags.py from Mike McCants' {info.filename} ({date}).\n"
        "// Standard magnitude (1000 km, 90° phase) by NORAD catalog number, for\n"
        "// CelesTrak's visual group. Do not edit by hand; overrides go in config.js.\n"
        f"export const STD_MAG = {{{body}}};\n"
        f"export const STD_MAG_DATE = '{date}';\n",
        encoding="utf-8",
    )
    missing = [i for i in ids if i not in mags]
    print(f"{OUT}: {len(found)} of {len(ids)} objects; no magnitude for {missing}")


if __name__ == "__main__":
    main()
