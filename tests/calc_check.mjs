// Same text apart from numbers that agree to ~1e-14 (last-digit differences in special
// functions and unit factors are fine).
const NUM = /-?\d+\.?\d*(?:e[-+]\d+)?/g;
function close(a, b) {
  if (a === null || a.replace(NUM, '#') !== b.replace(NUM, '#')) return false;
  const x = a.match(NUM) ?? [], y = b.match(NUM) ?? [];
  return x.every((v, i) => Math.abs(Number(v) - Number(y[i])) <= 1e-14 * Math.max(Math.abs(Number(v)), Math.abs(Number(y[i])), 1e-300));
}

const it = new Interp();
let fails = 0;
for (const [src, want] of CASES) {
  const { n, records } = it.run(src);
  const got = records.filter((r) => r.kind === 'out' || r.kind === 'err').map((r) => r.text).join('\n') || null;
  let ok;
  if (want === 'SYNTAX') ok = /SyntaxError/.test(got ?? '');
  else if (want === null) ok = got === null;
  else ok = got === want.replace('Cell In[N]', `Cell In[${n}]`) || close(got, want);
  if (!ok) {
    fails++;
    console.log(`FAIL  ${src}\n   want: ${JSON.stringify(want)}\n   got:  ${JSON.stringify(got)}`);
  }
}
// Help and completion
const help = (s) => it.run(s).records.map((r) => r.text).join('\n');
const checks = [
  ['sin? shows the docstring', /Signature:\s+sin\(x\)/.test(help('sin?'))],
  ['?km shows the unit', /length/.test(help('?km')) && /1000 m/.test(help('?km'))],
  ['c.c? shows the constant', /CODATA 2022/.test(help('c.c?'))],
  ['%units finds pressure units', /psi/.test(help('%units pressure'))],
  ['Tab completes units after a number', it.complete('3 GH').items.includes('GHz') && !it.complete('3 GH').items.includes('sqrt')],
  ['Tab completes units after ->', it.complete('x -> k').items.includes('km')],
  ['Tab completes units inside a chunk', it.complete('3 m / s').items.includes('s')],
  ['Tab completes names elsewhere', it.complete('mi').items.includes('min') && !it.complete('x + k').items.includes('km')],
  ['Tab completes sq', it.complete('sq').items.includes('sqrt')],
  ['Tab completes c.M_', it.complete('c.M_').items.includes('c.M_sun')],
  ['a unit shadowing a variable gets a note', /unit gram, not your variable g/.test(help('2 kg * g'))],
  ['no note in -> targets', !/Note/.test(help('3 m -> g / m'))],
  ['\\epsilon Tab gives ϵ', JSON.stringify(it.complete('x = \\epsilon')) === JSON.stringify({ start: 4, items: ['ϵ'], labels: ['\\epsilon ϵ'] })],
  ['\\varep Tab lists ε', it.complete('\\varep').items.join() === 'ε'],
  ['\\varp Tab lists ϖ and φ', it.complete('\\varp').items.join() === 'ϖ,φ'],
  ['\\^2 Tab gives ²', it.complete('m\\^2').items[0] === '²' && it.complete('m\\^2').start === 1],
  ['%whos lists variables', /Variable\s+Type/.test(help('%whos'))],
];
for (const [name, ok] of checks) {
  if (!ok) { fails++; console.log(`FAIL  ${name}`); }
}
console.log(fails ? `${fails} failure(s) of ${CASES.length + checks.length}` : `all ${CASES.length + checks.length} checks passed`);
process.exit(fails ? 1 : 0);
